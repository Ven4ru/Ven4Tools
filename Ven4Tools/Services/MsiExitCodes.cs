using System.Collections.Generic;

namespace Ven4Tools.Services
{
    /// <summary>
    /// Коды Windows Installer, которые и winget, и choco пробрасывают как есть, если
    /// пакет внутри — MSI. Раньше были продублированы в WingetErrorMapper и
    /// ChocoErrorMapper с разными комментариями о намерении пересекаться по этому
    /// диапазону — и всё равно разошлись (1633/1638 отсутствовали у choco, 1641 —
    /// у winget), хотя оба маппера — общий стандартный набор кодов установщика,
    /// не специфика конкретного пакетного менеджера.
    /// </summary>
    internal static class MsiExitCodes
    {
        public static readonly IReadOnlyDictionary<int, string> Known = new Dictionary<int, string>
        {
            { 1602, "Установка отменена в диалоге установщика." },
            { 1603, "Установщик пакета завершился с фатальной ошибкой." },
            { 1618, "Другая установка уже выполняется в системе — повторите позже." },
            { 1633, "Платформа установщика не поддерживается на этой системе." },
            { 1638, "Уже установлена другая версия этого продукта." },
            { 1641, "Установлено, инициирована перезагрузка." },
            { 3010, "Установлено, требуется перезагрузка." },
        };
    }
}
